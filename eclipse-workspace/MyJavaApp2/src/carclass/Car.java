package carclass;

public class Car {
		// This class represents a car with basic attributes and behaviors
	    String make; // The make of the car (e.g., Honda, Toyota)
	    String model; // The model of the car (e.g., Civic, Corolla)
	    int year; // The manufacturing year of the car
	    double speed; // The current speed of the car in mph

	    void accelerate() { // Increases the car's speed by 10 mph
	        speed = speed + 10;
	    }
	    void displaySpeed() { // Displays the current speed of the car in mph
	        System.out.println("Current speed: " + speed + "mph"); // Print the current speed of the car
	    }
	}

	
	
	    
	
	



